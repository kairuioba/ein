// 简报页顶部的「老板时间账本」：30 秒读完今天要不要你、团队在跑什么。
import { Clock3, Gauge, Users } from "lucide-react";

import { t } from "@/lib/i18n";
import { formatMinutes, formatRate, useMorningBrief } from "@/lib/owner-time";

const Stat = ({ icon, label, value }: { icon: React.ReactNode; label: string; value: string }) => (
  <div className="flex min-w-0 flex-1 flex-col gap-0.5 rounded-xl bg-raised px-3 py-2">
    <span className="flex items-center gap-1 text-[11px] text-ink-secondary">{icon}{label}</span>
    <b className="text-[18px] leading-tight text-ink">{value}</b>
  </div>
);

export function OwnerTimeCard() {
  const brief = useMorningBrief();
  if (!brief) return null;
  const headline =
    brief.headline === "decisions"
      ? t("{count} thing(s) need your decision", { count: brief.openDecisions })
      : brief.headline === "running"
        ? t("{count} project(s) running — nothing needs you right now", { count: brief.waitingProjects })
        : t("Nothing needs you right now.");
  return (
    <section className="mb-2 rounded-2xl bg-card p-3 shadow-[inset_0_0_0_1px_color-mix(in_oklab,var(--color-hairline)_55%,transparent)]">
      <div className="mb-2 flex items-center gap-2">
        <Gauge size={15} className="text-ink-secondary" />
        <b className="text-[13.5px] text-ink">{t("Your time today")}</b>
        <span className="min-w-0 flex-1 truncate text-right text-[11.5px] text-ink-secondary">{headline}</span>
      </div>
      <div className="flex flex-wrap gap-2">
        <Stat icon={<Users size={11} />} label={t("Waiting for you")} value={String(brief.openDecisions)} />
        <Stat icon={<Clock3 size={11} />} label={t("Running")} value={String(brief.waitingProjects)} />
        <Stat icon={<Gauge size={11} />} label={t("Decided today")} value={String(brief.decisionsToday)} />
      </div>
      <p className="mt-2 text-[11px] text-ink-secondary/80">
        {t("Decision latency p50: {minutes} min · rework rate {rate}", {
          minutes: formatMinutes(brief.decisionLatencyP50Ms),
          rate: formatRate(brief.reworkRate),
        })}
        <span className="ml-1 text-ink-secondary/55">{t("(numbers generated by code, not by a model)")}</span>
      </p>
    </section>
  );
}
